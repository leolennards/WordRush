#!/usr/bin/env node
/**
 * Regenerates the Wordskiis dictionary files in src/data/words/.
 *
 * Sources (both MIT-compatible, see src/data/words/SOURCES.md):
 *   - wordlist-english (SCOWL by Kevin Atkinson) — frequency tiers used to pick
 *     common words for the ANSWER list.
 *   - word-list (Sindre Sorhus) — broad list used for ACCEPTED guesses.
 *
 * IMPORTANT: the generated answers file is the source of truth for the daily
 * puzzle schedule. Regenerating it reorders future daily answers, so only do so
 * together with a DICTIONARY_VERSION bump in src/config/game.ts, and never
 * after launch unless you intend to change the schedule. To add answers later
 * without disturbing history, append them to the end of answers.ts by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const scowl = require('wordlist-english');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/data/words');

const FIVE = /^[a-z]{5}$/;
const five = (list) => list.filter((w) => FIVE.test(w));

// Every SCOWL word up to tier 50, used to detect inflected forms.
const known = new Set(
  Object.keys(scowl)
    .filter((k) => !/\/(55|60|70)$/.test(k))
    .flatMap((k) => scowl[k]),
);

const ANSWER_TIERS = ['10', '20', '35'].flatMap((t) => [
  `english/${t}`,
  `english/american/${t}`,
  `english/british/${t}`,
]);

function isInflection(w) {
  if (w.endsWith('s') && !w.endsWith('ss')) {
    if (known.has(w.slice(0, -1))) return true;
    if (w.endsWith('es') && known.has(w.slice(0, -2))) return true;
    if (w.endsWith('ies') && known.has(`${w.slice(0, -3)}y`)) return true;
  }
  if (w.endsWith('ed')) {
    if (known.has(w.slice(0, -1)) || known.has(w.slice(0, -2))) return true;
    if (w.endsWith('ied') && known.has(`${w.slice(0, -3)}y`)) return true;
    if (w[2] === w[3] && known.has(w.slice(0, -3))) return true;
  }
  return false;
}

// Hand-reviewed exclusions from the answer pool. These words remain valid
// guesses (if present in the guess dictionary); they are just never answers.
const EXCLUDED_ANSWERS = new Set(
  `
  bitch fagot penis pussy whore horny semen sperm kinky booby booty spank prick
  queer nappy slave nuder lusty bawdy buxom nymph bosom gayer harem chink lynch
  idiot moron dunce ninny bigot sissy fatty obese loony leper
  feces urine vomit enema mucus bowel groin uteri ovary fetus polyp polio opium
  gonna wanna gimme kinda lemme sorta dunno
  abler apter barer baser coyer direr huger lamer laxer liker muter rawer rifer
  sager shyer slier slyer sorer wryer icier freer purer ruder riper surer viler
  cuter paler truer saner odder drier drily weest
  acing aping awing axing cuing eking ruing suing upped pends feted redid undid
  dimer haler halon octal infix sizer edger fiche genii unman unsay unset sunup
  letup inter maria peter roman bible mamma miaow pokey multi whizz trump pagan
  fiber fibre liter litre metre saber sabre mould moult odour enrol appal baulk
  moldy arbor ardor armor favor honor humor labor rigor rumor savor tumor valor
  vapor vigor color furor fiver
  `
    .trim()
    .split(/\s+/),
);

const candidates = [...new Set(ANSWER_TIERS.flatMap((k) => five(scowl[k] ?? [])))].sort();
const answers = candidates.filter((w) => !isInflection(w) && !EXCLUDED_ANSWERS.has(w));

const guessWords = readFileSync(join(root, 'node_modules/word-list/words.txt'), 'utf8')
  .split('\n')
  .map((w) => w.trim().toLowerCase());
const scowlGuesses = [...known];
const allowed = [...new Set([...five(guessWords), ...five(scowlGuesses), ...answers])].sort();

// Deterministic shuffle (mulberry32 + Fisher–Yates) so the daily schedule is
// not alphabetical but is fully reproducible.
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(20261001);
const shuffled = [...answers];
for (let i = shuffled.length - 1; i > 0; i--) {
  const j = Math.floor(rand() * (i + 1));
  [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
}

const header = `// GENERATED by scripts/build-words.mjs — see SOURCES.md for provenance and licences.\n`;
const chunk = (list) => {
  const lines = [];
  for (let i = 0; i < list.length; i += 12) lines.push(list.slice(i, i + 12).join(' '));
  return lines.join('\n');
};

writeFileSync(
  join(outDir, 'answers.ts'),
  `${header}// Order is significant: it defines the daily schedule. Append only.\n` +
    `const RAW = \`\n${chunk(shuffled)}\n\`;\n\n` +
    `export const ANSWERS: readonly string[] = Object.freeze(RAW.trim().split(/\\s+/));\n`,
);
writeFileSync(
  join(outDir, 'allowed.ts'),
  `${header}// Accepted guesses (answers are merged in at runtime as well).\n` +
    `const RAW = \`\n${chunk(allowed)}\n\`;\n\n` +
    `export const ALLOWED_GUESSES: readonly string[] = Object.freeze(RAW.trim().split(/\\s+/));\n`,
);

console.log(`answers: ${shuffled.length}, accepted guesses: ${allowed.length}`);
